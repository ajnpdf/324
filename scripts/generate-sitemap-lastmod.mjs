import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = process.cwd();
const sitemapFile = path.join(root, 'src', 'app', 'sitemap.ts');
const toolIdsFile = path.join(root, 'scripts', 'r13-public-tool-ids.json');
const outputFile = path.join(root, 'src', 'generated', 'sitemap-lastmod.ts');

function git(args) {
  try {
    return execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return '';
  }
}

function latestDate(paths) {
  const existing = paths.filter((candidate) => fs.existsSync(path.join(root, candidate)));
  if (!existing.length) return '';
  return git(['log', '-1', '--format=%cI', '--', ...existing]);
}

function normalizePath(value) {
  if (!value || value === '/') return '/';
  return `/${value.replace(/^\/+|\/+$/g, '')}`;
}

function staticCandidates(urlPath) {
  const normalized = normalizePath(urlPath);
  if (normalized === '/') return ['src/app/page.tsx', 'src/app/layout.tsx'];
  const relative = normalized.replace(/^\//, '');
  return [
    `src/app/${relative}/page.tsx`,
    `src/app/${relative}/layout.tsx`,
    `src/app/${relative}/route.ts`,
  ];
}

const headDate = git(['show', '-s', '--format=%cI', 'HEAD']);
if (!headDate && fs.existsSync(outputFile)) {
  console.warn('WARN: Git history is unavailable; preserving existing sitemap lastmod manifest.');
  process.exit(0);
}
if (!headDate) throw new Error('Git history is unavailable and no sitemap lastmod manifest exists.');

const sitemapSource = fs.readFileSync(sitemapFile, 'utf8');
const staticPaths = [...sitemapSource.matchAll(/\{\s*path:\s*'([^']+)'/g)].map((match) => normalizePath(match[1]));
const toolIds = JSON.parse(fs.readFileSync(toolIdsFile, 'utf8'));

const toolSharedSources = [
  'src/lib/tools-data.ts',
  'src/lib/conversion-tools.ts',
  'src/lib/tool-editorial.ts',
  'src/lib/seo-strategy.ts',
  'src/lib/tool-limits.ts',
  'src/app/(tool-pages)/[id]/page.tsx',
];
const toolSharedDate = latestDate(toolSharedSources) || headDate;

const entries = new Map();
for (const urlPath of staticPaths) {
  entries.set(urlPath, latestDate(staticCandidates(urlPath)) || headDate);
}
for (const id of toolIds) {
  entries.set(normalizePath(id), toolSharedDate);
}

const ordered = [...entries.entries()].sort(([a], [b]) => a.localeCompare(b));
const lines = [
  '// AUTO-GENERATED by scripts/generate-sitemap-lastmod.mjs.',
  '// Values come from Git commit history of route/content source files, never build time.',
  `export const SITEMAP_FALLBACK_LASTMOD = ${JSON.stringify(headDate)};`,
  'export const SITEMAP_LASTMOD: Record<string, string> = {',
  ...ordered.map(([urlPath, date]) => `  ${JSON.stringify(urlPath)}: ${JSON.stringify(date)},`),
  '};',
  '',
  'export function getSitemapLastModified(pathname: string): string {',
  "  const normalized = !pathname || pathname === '/' ? '/' : `/${pathname.replace(/^\\/+|\\/+$/g, '')}`;",
  '  return SITEMAP_LASTMOD[normalized] || SITEMAP_FALLBACK_LASTMOD;',
  '}',
  '',
];

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, `${lines.join('\n')}\n`, 'utf8');
console.log(`PASS: sitemap lastmod manifest generated for ${ordered.length} canonical routes from Git history.`);
